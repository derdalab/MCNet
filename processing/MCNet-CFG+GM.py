def prepare_data(data, batch_size = 64, mode = 'train'):
    """Prepare inputs and desired outputs for training or testing.
    weighted: To weight the data or not. Default: False.
    mode: Set to 'test' or 'train'. Default: 'train'."""

    tensors = []
    for name, features, values in data:
        input_tensor = torch.tensor(features).float().to(device)
        value_tensor = torch.tensor(values).float().to(device)

        tensors.append( (input_tensor, value_tensor) )

    return torch.utils.data.DataLoader(tensors, batch_size = batch_size)




