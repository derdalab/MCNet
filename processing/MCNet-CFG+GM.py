def early_stop(losses, patience):
    """Return True if the loss hasn't improved for a number of epochs.
    patience: Number of epochs without improvement."""
    if min(losses) < min(losses[-patience:]):
        return True

def weighted_MSE(x, target, weights):
    """An alternation of calculating the data's MSE, in which we include the
    weights of the data. This function is adapted from
    https://discuss.pytorch.org/t/pixelwise-weights-for-mseloss/1254."""
    delta = x - target
    return ((delta * delta) * weights.expand_as(delta)).sum(0)

def myLoss(output, target):
    delta = (output - target) * (target > 0)
    loss = torch.mean(delta**2)
    return loss

def train(plot = False, weight_decay = 1e-4, patience = 10, torch_seed= 0,**kwargs):

#          fold_seed = None, n_samples = 1, 
#   n_hidden_neurons=100, n_hidden_layers=1, 
#          n_datasets = 1257, dataset_offset = 0, permute_seed = None

    """Train GlyNet using 10-fold cross-validation on the CFG data.
    n_hidden_neurons: Number of neurons in a each hidden layer. Default: 800.
    n_hidden_layers: Number of hidden layers. Default: 1.
    decay: Weight decay. Default: 1e-4.
    patience: Number of epochs without improvement. Default: 10.
    thres: Values below thres at set to thres. Default: None.
    n_cutoff: Number of values to be removed. Default: 0.
    weighted: To weight the data or not. Default: False.
    choice: Choice of sample. If None, all samples used. Default: None
    plot: Plot loss for every epoch. Default: False"""

    parameters = locals()
    del parameters['plot'], parameters['kwargs']

    data, extra_data, output_names, in_dim, out_dim, data_parameters = get_data(**kwargs)
    parameters.update(data_parameters)

    net = GlyNet(in_dim, out_dim, **kwargs).to(device)
    parameters.update(net.get_parameters())

    #print(in_dim, out_dim, n_hidden_neurons, n_hidden_layers)
    ###criterion = torch.nn.MSELoss()
    optimizer = torch.optim.Adam(net.parameters(), weight_decay = weight_decay)

    input_n   = numpy.zeros((0, in_dim),  dtype = numpy.float32)
    actual    = numpy.zeros((0, out_dim), dtype = numpy.float32)
    predicted = numpy.zeros((0, out_dim), dtype = numpy.float32)
    extra_eval= numpy.zeros((0, out_dim), dtype = numpy.float32)
    
    glycans, fold_num, extra_names_all = [], [], []
    for i, (held_out, kept_in) in enumerate(kfold_pnrg(data, parameters, **kwargs)):
        start_time = time.time()
        train_losses, test_losses = [], []
        trainloader = prepare_data(kept_in)
        print('Fold', i + 1, 'Held Out')
  
        # Initialize for per-fold training
        torch.manual_seed(torch_seed)
        for layers in net.children():
            for layer in layers:
                layer.reset_parameters()

        for epoch in range(1000):
            batch_loss = 0.0
            for inputs, values in trainloader:  ### prepare_data(kept_in):
                #print('Begin:', epoch)
                optimizer.zero_grad()
                outputs = net(inputs)
                ###loss = criterion(values, outputs)
                loss = myLoss(outputs, values)
                loss.backward()
                optimizer.step()
                batch_size, _ = values.size()
                batch_loss += loss.item() * batch_size
            train_loss = batch_loss / len(kept_in)
            train_losses.append(train_loss)

            ### check loss on the testing set
            names, test_inputs, test_values = prepare_data_compare(held_out)
            with torch.no_grad():
                test_outputs = net(test_inputs)
                ###test_loss = criterion(test_values, test_outputs)
                test_loss = myLoss(test_outputs, test_values)
            test_losses.append(test_loss.item())

            print('    Monitor: {} {} {} {}'.format(len(test_losses),
                      time.time() - start_time, train_loss, test_loss.item()))
            if early_stop(test_losses, patience):
                break

        # after all the training epochs - evaluate the extra dataset
        extra_names, extra_inputs = prepare_data_eval(extra_data)
        with torch.no_grad():
            extra_outputs = net(extra_inputs)

        glycans += [name for name, fingpr, rfu in held_out]
        fold_num += [i for x in held_out]
        input_n   = numpy.append(input_n,   test_inputs.numpy(),  axis = 0)
        actual    = numpy.append(actual,    test_values.numpy(),  axis = 0)
        predicted = numpy.append(predicted, test_outputs.numpy(), axis = 0)

        extra_names_all.extend(extra_names)
        extra_eval = numpy.append(extra_eval, extra_outputs.numpy(), axis = 0)

        print('Train Loss:', round(train_loss, 4))
        print('Test Loss:', round(test_loss.item(), 4))
        torch.save(net.state_dict(), '{}/trained_model-{}.pt'. format(result_dir, i))
        
    print('GlyNet Cross-Validation Complete')
 
    ###act_data  = pandas.DataFrame(actual, columns=output_names, index=glycans)
    ###pred_data = pandas.DataFrame(predicted, columns=output_names, index=glycans)
    input_data  = pandas.DataFrame(input_n, index=glycans)
    act_data    = pandas.DataFrame(actual, index=glycans, columns = output_names)
    pred_data   = pandas.DataFrame(predicted, index=glycans, columns = output_names)
    fold_data   = pandas.DataFrame(fold_num, index=glycans)

    print('EEEE:', len(extra_names_all), extra_eval.shape)
    extra_eval  = pandas.DataFrame(extra_eval, index = extra_names_all, columns = output_names)
    monitor_data = [time.time() - start_time, epoch, train_loss, test_loss]
   
    print('Sizes:', act_data.shape, pred_data.shape, fold_data.shape)
    ###print(act_data.iloc[0])
    ###print(pred_data.iloc[0])
 
    return input_data, act_data, pred_data, fold_data, monitor_data, extra_eval, parameters


